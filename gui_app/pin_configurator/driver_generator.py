"""
Zephyr Driver Boilerplate Generator.

Generates complete Zephyr driver scaffolding from templates, following the
patterns established by the Swedish Embedded SDK:
  - DT_DRV_COMPAT compatible string
  - DEVICE_DT_INST_DEFINE instantiation macro
  - Proper config/data struct separation
  - Kconfig option for enabling the driver
  - CMakeLists.txt with conditional compilation

Supported driver types:
  - sensor   (Sensor API: sensor_sample_fetch / sensor_channel_get)
  - gpio     (GPIO driver API)
  - i2c      (I2C device on a bus)
  - spi      (SPI device on a bus)
  - uart     (UART/serial driver)
  - pwm      (PWM output driver)
  - adc      (ADC channel driver)
  - custom   (Bare DEVICE_DT_INST_DEFINE skeleton)
"""

from __future__ import annotations

import os
import textwrap
from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional


# ── Data model ────────────────────────────────────────────────────────

@dataclass
class DriverSpec:
    """Specification for a Zephyr driver to be generated."""
    name: str                          # e.g. "my_sensor"
    driver_type: str                   # sensor, gpio, i2c, spi, uart, pwm, adc, custom
    compatible: str                    # DT compatible string, e.g. "vendor,my-sensor"
    bus: str = "i2c"                   # bus type: i2c, spi, or none
    description: str = ""              # Human-readable description
    vendor: str = ""                   # Vendor name for Kconfig
    has_interrupt: bool = False        # Whether to add IRQ handling boilerplate
    num_channels: int = 1              # Number of sensor channels (sensor type only)
    registers: list[RegisterDef] = field(default_factory=list)
    author: str = "Pyontrust Generator"
    year: str = field(default_factory=lambda: str(datetime.now().year))


@dataclass
class RegisterDef:
    """A device register definition."""
    name: str       # e.g. "REG_WHO_AM_I"
    address: int    # e.g. 0x0F
    size: int = 1   # bytes
    rw: str = "RO"  # RO, WO, RW


@dataclass
class GeneratedDriver:
    """The complete set of generated driver files."""
    source_c: str           # drivers/<type>/<name>.c
    header_h: str           # include/<name>.h (optional public header)
    kconfig: str            # Kconfig snippet
    cmake: str              # CMakeLists.txt snippet
    overlay_sample: str     # Sample DTS overlay
    prj_conf_sample: str    # Sample prj.conf
    readme: str             # README.md
    test_c: Optional[str] = None  # Optional unit test skeleton


# ── Template strings ──────────────────────────────────────────────────

_SPDX = "/* SPDX-License-Identifier: Apache-2.0 */"

_SENSOR_TEMPLATE = """\
{spdx}
/**
 * @file {name}.c
 * @brief Zephyr sensor driver for {compatible}
 *
 * Generated by Pyontrust Pin Configurator.
 * {description}
 */

#include <zephyr/device.h>
#include <zephyr/drivers/sensor.h>
{bus_includes}
#include <zephyr/logging/log.h>

LOG_MODULE_REGISTER({name}, CONFIG_{NAME}_LOG_LEVEL);

#define DT_DRV_COMPAT {compat_underscore}

/* ── Register definitions ─────────────────────────────────────────── */

{register_defines}

/* ── Driver data & config ─────────────────────────────────────────── */

struct {name}_config {{
{config_struct}
}};

struct {name}_data {{
{data_struct}
}};

/* ── Bus helpers ──────────────────────────────────────────────────── */

{bus_helpers}

/* ── Sensor API ───────────────────────────────────────────────────── */

static int {name}_sample_fetch(const struct device *dev,
                               enum sensor_channel chan)
{{
    struct {name}_data *data = dev->data;
    const struct {name}_config *cfg = dev->config;

    /* TODO: Read sensor registers and update data->last_sample */
    LOG_DBG("sample_fetch called");

    return 0;
}}

static int {name}_channel_get(const struct device *dev,
                              enum sensor_channel chan,
                              struct sensor_value *val)
{{
    struct {name}_data *data = dev->data;

    switch (chan) {{
    case SENSOR_CHAN_ALL:
        /* TODO: Fill val with the appropriate channel data */
        val->val1 = 0;
        val->val2 = 0;
        break;
    default:
        return -ENOTSUP;
    }}

    return 0;
}}

{irq_handler}

static const struct sensor_driver_api {name}_api = {{
    .sample_fetch = {name}_sample_fetch,
    .channel_get  = {name}_channel_get,
{trigger_api}
}};

/* ── Init ─────────────────────────────────────────────────────────── */

static int {name}_init(const struct device *dev)
{{
    const struct {name}_config *cfg = dev->config;

    LOG_INF("{name} initialized on %s", dev->name);
{bus_init}
{irq_init}
    return 0;
}}

/* ── Instantiation ────────────────────────────────────────────────── */

#define {NAME}_INST(inst)                                                   \\
    static struct {name}_data {name}_data_##inst;                           \\
                                                                            \\
    static const struct {name}_config {name}_config_##inst = {{              \\
{config_init_macro}
    }};                                                                     \\
                                                                            \\
    DEVICE_DT_INST_DEFINE(inst,                                             \\
                          {name}_init,                                       \\
                          NULL,                                              \\
                          &{name}_data_##inst,                               \\
                          &{name}_config_##inst,                             \\
                          POST_KERNEL,                                       \\
                          CONFIG_{NAME}_INIT_PRIORITY,                       \\
                          &{name}_api);

DT_INST_FOREACH_STATUS_OKAY({NAME}_INST)
"""

