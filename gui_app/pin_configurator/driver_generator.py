# ── Generator functions ───────────────────────────────────────────────

def _compat_to_underscore(compatible: str) -> str:
    """Convert DT compatible 'vendor,my-sensor' → 'vendor_my_sensor'."""
    return compatible.replace(",", "_").replace("-", "_")


def _generate_register_defines(registers: list[RegisterDef]) -> str:
    if not registers:
        return "/* No registers defined — add your own here */\n"
    lines = []
    for reg in registers:
        lines.append(f"#define {reg.name:30s} 0x{reg.address:02X}  "
                     f"/* {reg.rw}, {reg.size} byte(s) */")
    return "\n".join(lines)


def _bus_includes(bus: str) -> str:
    if bus == "i2c":
        return "#include <zephyr/drivers/i2c.h>"
    elif bus == "spi":
        return "#include <zephyr/drivers/spi.h>"
    return ""


def _bus_config_fields(bus: str, name: str) -> str:
    if bus == "i2c":
        return "    struct i2c_dt_spec i2c;"
    elif bus == "spi":
        return ("    struct spi_dt_spec spi;\n"
                "    struct gpio_dt_spec cs_gpio;")
    return "    /* No bus */"


def _bus_data_fields(name: str) -> str:
    return "    int32_t last_sample;"


def _bus_helpers(bus: str, name: str) -> str:
    if bus == "i2c":
        return textwrap.dedent(f"""\
            static int {name}_reg_read(const struct device *dev,
                                       uint8_t reg, uint8_t *val, uint8_t len)
            {{
                const struct {name}_config *cfg = dev->config;
                return i2c_burst_read_dt(&cfg->i2c, reg, val, len);
            }}

            static int {name}_reg_write(const struct device *dev,
                                        uint8_t reg, uint8_t val)
            {{
                const struct {name}_config *cfg = dev->config;
                return i2c_reg_write_byte_dt(&cfg->i2c, reg, val);
            }}""")
    elif bus == "spi":
        return f"/* TODO: Add SPI read/write helpers for {name} */"
    return ""


def _bus_init_code(bus: str, name: str) -> str:
    if bus == "i2c":
        return textwrap.dedent(f"""\
                if (!i2c_is_ready_dt(&cfg->i2c)) {{
                    LOG_ERR("I2C bus not ready");
                    return -ENODEV;
                }}""")
    elif bus == "spi":
        return textwrap.dedent(f"""\
                if (!spi_is_ready_dt(&cfg->spi)) {{
                    LOG_ERR("SPI bus not ready");
                    return -ENODEV;
                }}""")
    return ""


def _config_init_macro(bus: str, name: str) -> str:
    if bus == "i2c":
        return f"        .i2c = I2C_DT_SPEC_INST_GET(inst),                             \\"
    elif bus == "spi":
        return (f"        .spi = SPI_DT_SPEC_INST_GET(inst, SPI_WORD_SET(8), 0),        \\\n"
                f"        .cs_gpio = GPIO_DT_SPEC_INST_GET(inst, cs_gpios),               \\")
    return "        /* No bus-specific config */                                    \\"


def _irq_handler(name: str, has_interrupt: bool) -> str:
    if not has_interrupt:
        return ""
    return textwrap.dedent(f"""\
        /* ── IRQ handling ─────────────────────────────────────────────────── */

        static void {name}_irq_handler(const struct device *dev)
        {{
            struct {name}_data *data = dev->data;

            LOG_DBG("IRQ fired");
            /* TODO: Read status register, clear interrupt, notify */
        }}
        """)


def _trigger_api(has_interrupt: bool) -> str:
    if not has_interrupt:
        return ""
    return "    /* .trigger_set = ... */  /* TODO: add trigger support */"


def _irq_init(name: str, has_interrupt: bool) -> str:
    if not has_interrupt:
        return ""
    return textwrap.dedent(f"""\
            /* TODO: Configure and enable interrupt line */
        """)


def generate_sensor_driver(spec: DriverSpec) -> str:
    """Generate a sensor driver .c file."""
    NAME = spec.name.upper()
    return _SENSOR_TEMPLATE.format(
        spdx=_SPDX,
        name=spec.name,
        NAME=NAME,
        compatible=spec.compatible,
        compat_underscore=_compat_to_underscore(spec.compatible),
        description=spec.description,
        bus_includes=_bus_includes(spec.bus),
        register_defines=_generate_register_defines(spec.registers),
        config_struct=_bus_config_fields(spec.bus, spec.name),
        data_struct=_bus_data_fields(spec.name),
        bus_helpers=_bus_helpers(spec.bus, spec.name),
        bus_init=_bus_init_code(spec.bus, spec.name),
        config_init_macro=_config_init_macro(spec.bus, spec.name),
        irq_handler=_irq_handler(spec.name, spec.has_interrupt),
        trigger_api=_trigger_api(spec.has_interrupt),
        irq_init=_irq_init(spec.name, spec.has_interrupt),
    )


def generate_custom_driver(spec: DriverSpec) -> str:
    """Generate a bare-bones custom driver .c file."""
    return _CUSTOM_TEMPLATE.format(
        spdx=_SPDX,
        name=spec.name,
        NAME=spec.name.upper(),
        compatible=spec.compatible,
        compat_underscore=_compat_to_underscore(spec.compatible),
        description=spec.description,
    )


def generate_kconfig(spec: DriverSpec) -> str:
    """Generate a Kconfig file for the driver."""
    NAME = spec.name.upper()
    bus_dep = ""
    if spec.bus == "i2c":
        bus_dep = "\n\tselect I2C"
    elif spec.bus == "spi":
        bus_dep = "\n\tselect SPI"

    return textwrap.dedent(f"""\
        # SPDX-License-Identifier: Apache-2.0

        config {NAME}
        \tbool "Enable {spec.name} driver"
        \tdefault y
        \tdepends on DT_HAS_{_compat_to_underscore(spec.compatible).upper()}_ENABLED{bus_dep}
        \thelp
        \t  Enable the {spec.name} driver for {spec.compatible} devices.
        \t  {spec.description}

        if {NAME}

        config {NAME}_INIT_PRIORITY
        \tint "{spec.name} init priority"
        \tdefault 90
        \thelp
        \t  Initialization priority for the {spec.name} driver.

        config {NAME}_LOG_LEVEL
        \tint "{spec.name} log level"
        \tdefault 4
        \trange 0 4
        \thelp
        \t  Log level for the {spec.name} driver (0=OFF, 4=DBG).

        endif # {NAME}
    """)


def generate_cmake(spec: DriverSpec) -> str:
    """Generate a CMakeLists.txt snippet for the driver."""
    NAME = spec.name.upper()
    return textwrap.dedent(f"""\
        # SPDX-License-Identifier: Apache-2.0

        zephyr_library_sources_ifdef(CONFIG_{NAME} {spec.name}.c)
    """)


def generate_overlay_sample(spec: DriverSpec) -> str:
    """Generate a sample DTS overlay for using the driver."""
    if spec.bus == "i2c":
        return textwrap.dedent(f"""\
            /* Sample DTS overlay for {spec.compatible} on I2C bus */
            &i2c0 {{
                status = "okay";

                {spec.name}: {spec.name}@XX {{
                    compatible = "{spec.compatible}";
                    reg = <0xXX>;  /* TODO: Set I2C address */
                    status = "okay";
                }};
            }};
        """)
    elif spec.bus == "spi":
        return textwrap.dedent(f"""\
            /* Sample DTS overlay for {spec.compatible} on SPI bus */
            &spi0 {{
                status = "okay";

                {spec.name}: {spec.name}@0 {{
                    compatible = "{spec.compatible}";
                    reg = <0>;
                    spi-max-frequency = <1000000>;
                    status = "okay";
                }};
            }};
        """)
    return textwrap.dedent(f"""\
        /* Sample DTS overlay for {spec.compatible} */
        / {{
            {spec.name}: {spec.name} {{
                compatible = "{spec.compatible}";
                status = "okay";
            }};
        }};
    """)


def generate_prj_conf_sample(spec: DriverSpec) -> str:
    """Generate a sample prj.conf."""
    NAME = spec.name.upper()
    lines = [
        f"# Enable the {spec.name} driver",
        f"CONFIG_{NAME}=y",
        f"CONFIG_{NAME}_LOG_LEVEL=4",
    ]
    if spec.driver_type == "sensor":
        lines.append("CONFIG_SENSOR=y")
    if spec.bus == "i2c":
        lines.append("CONFIG_I2C=y")
    elif spec.bus == "spi":
        lines.append("CONFIG_SPI=y")
    lines.append("CONFIG_LOG=y")
    return "\n".join(lines) + "\n"


def generate_readme(spec: DriverSpec) -> str:
    """Generate a README.md for the driver."""
    return textwrap.dedent(f"""\
        # {spec.name} Driver

        {spec.description or f"Zephyr driver for {spec.compatible} devices."}

        ## Driver Type

        - **Type**: {spec.driver_type}
        - **Bus**: {spec.bus}
        - **Compatible**: `{spec.compatible}`

        ## Building

        ```bash
        west build -p -b <your_board> .
        ```

        ## Testing

        ```bash
        west build -t testbench    # Interactive Renode simulation
        west build -t robotbench   # Automated RobotFramework test
        ```

        ## Files

        | File | Purpose |
        |------|---------|
        | `{spec.name}.c` | Driver implementation |
        | `Kconfig` | Enable/configure the driver |
        | `CMakeLists.txt` | Build system integration |

        ## Generated by

        Pyontrust Pin Configurator — {spec.year}
    """)


def generate_test_skeleton(spec: DriverSpec) -> str:
    """Generate a unit test skeleton (CMock/Unity style, inspired by SE-SDK)."""
    NAME = spec.name.upper()
    return textwrap.dedent(f"""\
        /* SPDX-License-Identifier: Apache-2.0 */
        /**
         * @file test_{spec.name}.c
         * @brief Unit tests for {spec.name} driver
         *
         * Uses Unity test framework (CMock for mocking).
         * Inspired by Swedish Embedded SDK testing patterns.
         */

        #include <unity.h>
        #include <zephyr/ztest.h>
        #include <zephyr/device.h>

        #define {NAME}_NODE DT_NODELABEL({spec.name})

        ZTEST_SUITE({spec.name}_tests, NULL, NULL, NULL, NULL, NULL);

        ZTEST({spec.name}_tests, test_device_ready)
        {{
            const struct device *dev = DEVICE_DT_GET({NAME}_NODE);
            zassert_true(device_is_ready(dev), "Device not ready");
        }}

        ZTEST({spec.name}_tests, test_sample_fetch)
        {{
            const struct device *dev = DEVICE_DT_GET({NAME}_NODE);
            int ret = sensor_sample_fetch(dev);
            zassert_equal(ret, 0, "sample_fetch failed: %d", ret);
        }}

        ZTEST({spec.name}_tests, test_channel_get)
        {{
            const struct device *dev = DEVICE_DT_GET({NAME}_NODE);
            struct sensor_value val;

            sensor_sample_fetch(dev);
            int ret = sensor_channel_get(dev, SENSOR_CHAN_ALL, &val);
            zassert_equal(ret, 0, "channel_get failed: %d", ret);
        }}
    """)


# ── Main entry point ──────────────────────────────────────────────────

DRIVER_TYPES = ["sensor", "gpio", "i2c", "spi", "uart", "pwm", "adc", "custom"]


def generate_driver(spec: DriverSpec) -> GeneratedDriver:
    """
    Generate a complete Zephyr driver package from a specification.

    Returns a GeneratedDriver with all file contents.
    """
    if spec.driver_type == "sensor":
        source = generate_sensor_driver(spec)
    else:
        source = generate_custom_driver(spec)

    return GeneratedDriver(
        source_c=source,
        header_h="",  # TODO: public header generation
        kconfig=generate_kconfig(spec),
        cmake=generate_cmake(spec),
        overlay_sample=generate_overlay_sample(spec),
        prj_conf_sample=generate_prj_conf_sample(spec),
        readme=generate_readme(spec),
        test_c=generate_test_skeleton(spec) if spec.driver_type == "sensor" else None,
    )


def driver_to_json(drv: GeneratedDriver) -> dict:
    """Convert a GeneratedDriver to a JSON-serializable dict."""
    return {
        "source_c": drv.source_c,
        "header_h": drv.header_h,
        "kconfig": drv.kconfig,
        "cmake": drv.cmake,
        "overlay_sample": drv.overlay_sample,
        "prj_conf_sample": drv.prj_conf_sample,
        "readme": drv.readme,
        "test_c": drv.test_c,
    }


def spec_from_json(data: dict) -> DriverSpec:
    """Create a DriverSpec from a JSON request body."""
    registers = []
    for r in data.get("registers", []):
        registers.append(RegisterDef(
            name=r.get("name", "REG_UNKNOWN"),
            address=r.get("address", 0),
            size=r.get("size", 1),
            rw=r.get("rw", "RO"),
        ))

    return DriverSpec(
        name=data.get("name", "my_driver"),
        driver_type=data.get("driver_type", "custom"),
        compatible=data.get("compatible", "vendor,my-device"),
        bus=data.get("bus", "i2c"),
        description=data.get("description", ""),
        vendor=data.get("vendor", ""),
        has_interrupt=data.get("has_interrupt", False),
        num_channels=data.get("num_channels", 1),
        registers=registers,
    )
